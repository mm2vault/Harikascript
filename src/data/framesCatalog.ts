// Helper to quickly build frames with consistent styling and high aesthetic quality
function createFrame(
  id: string,
  name: string,
  gender: 'female' | 'male' | 'unisex',
  theme: string,
  tagText: string,
  description: string,
  price: number,
  rarity: 'common' | 'rare' | 'epic' | 'legendary' | 'mythic',
  style: FrameStyleConfig,
  isPopular = false,
  isNew = false
): Product {
  return {
    id,
    name,
    category: 'frames',
    gender,
    theme,
    tagText,
    description,
    price,
    isAnimated: true,
    frameType: id,
    frameStyle: style,
    rarity,
    isPopular,
    isNew
  };
}

